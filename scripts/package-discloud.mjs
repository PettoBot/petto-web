// Gathers what Discloud needs to run the site, already built, into one folder (default `discloud-dist/`):
// the compiled site, the launcher, discloud.config and a package.json that has only the packages the site needs to run
// and no build script, so Discloud has nothing to compile. The `Discloud prebuilt` workflow runs this after a build and
// pushes the folder to the `discloud` branch; it can also be run by hand: `npm run build:discloud && npm run package:discloud`.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const out = resolve(process.argv[2] ?? 'discloud-dist');

if (!existsSync('build/dist/server/entry.mjs') || !existsSync('build/.built')) {
  console.error('There is no finished Discloud build. Run `npm run build:discloud` first.');
  process.exit(1);
}

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

cpSync('build', resolve(out, 'build'), { recursive: true });
cpSync('server.mjs', resolve(out, 'server.mjs'));
cpSync('discloud.config', resolve(out, 'discloud.config'));

// Packages only the build or the Cloudflare host use: the compiled site does not load them when it runs on Node.
const buildOnly = new Set(['@astrojs/cloudflare', '@astrojs/sitemap', '@types/react', '@types/react-dom', '@flaticon/flaticon-uicons', 'dotenv']);
const dependencies = Object.fromEntries(Object.entries(pkg.dependencies).filter(([name]) => !buildOnly.has(name)));

const runtime = {
  name: pkg.name,
  version: pkg.version,
  private: true,
  type: pkg.type,
  scripts: { 'start:discloud': 'node server.mjs' },
  dependencies,
};
writeFileSync(resolve(out, 'package.json'), `${JSON.stringify(runtime, null, 2)}\n`);
writeFileSync(resolve(out, 'README.md'), 'Built output of petto-web for Discloud. Generated by the `Discloud prebuilt` workflow from the main branch; do not edit by hand.\n');

console.log(`Packaged petto-web ${pkg.version} into ${out}`);
