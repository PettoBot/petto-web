export type AppealKey = keyof typeof text.en;

/** A translator: `at('needs', { types: 'ban' })`. Missing keys fall back to English. */
export function appealText(lang: AppealLang) {
  const catalog = (text[lang] ?? text.en) as Record<string, string>;
  return (key: AppealKey, vars: Record<string, string | number> = {}): string => {
    const raw = catalog[key] ?? (text.en as Record<string, string>)[key] ?? key;
    return raw.replace(/\{(\w+)\}/g, (_m, name) => String(vars[name] ?? ''));
  };
}
export const asAppealLang = (value: unknown): AppealLang => (value === 'es' ? 'es' : value === 'pt-BR' || value === 'pt' ? 'pt-BR' : 'en');
